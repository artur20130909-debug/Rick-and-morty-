-- переводим ключи в плоские массивы чисел: kf[i] = { t, e, vals = { T = {6 чисел}, ... } }
local FIELDS = { "p", "y", "r", "x", "u", "f" }
local JOINTS = { "T", "H", "RA", "LA", "RL", "LL" }
Poses.FIELDS = FIELDS
Poses.JOINTS = JOINTS

local function vec(j)
	local v = {}
	for i, f in ipairs(FIELDS) do v[i] = (j and j[f]) or 0 end
	return v
end
Poses.vec = vec

local function prepare(anim)
	local mask = {}
	for _, k in ipairs(anim.k) do
		for _, j in ipairs(JOINTS) do if k.p[j] then mask[j] = true end end
	end
	local prev = {}
	local frames = {}
	for i, k in ipairs(anim.k) do
		local vals = {}
		for j in pairs(mask) do
			local src = k.p[j]
			if src then
				local base = prev[j] or vec(nil)
				local v = {}
				for fi, f in ipairs(FIELDS) do
					if src[f] ~= nil then v[fi] = src[f] else v[fi] = base[fi] end
				end
				vals[j] = v
			else
				vals[j] = prev[j] or vec(nil)
			end
			prev[j] = vals[j]
		end
		frames[i] = { t = k.t, e = k.e, vals = vals }
	end
	anim.frames = frames
	anim.mask = mask
	anim.fi = anim.fi or 0.05
	anim.fo = anim.fo or 0.1
end
for _, anim in pairs(A) do
	if not anim.frames then prepare(anim) end
end

