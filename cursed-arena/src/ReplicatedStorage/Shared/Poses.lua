	if e == "lin" then return a end
	if e == "in" then return a * a end
	if e == "out" then return 1 - (1 - a) * (1 - a) end
	if e == "back" then
		local c1 = 1.70158
		local c3 = c1 + 1
		local x = a - 1
		return 1 + c3 * x * x * x + c1 * x * x
	end
	return a < 0.5 and 2 * a * a or 1 - ((-2 * a + 2) ^ 2) / 2
end
Poses.ease = ease

-- значение анимации в момент t: out[j] = {6 чисел} только для суставов маски
function Poses.sample(anim, t, out)
	local frames = anim.frames
	local n = #frames
	if anim.loop then
		t = t % anim.d
	end
	local i = 1
	while i < n and frames[i + 1].t <= t do i = i + 1 end
	local a, b = frames[i], frames[math.min(i + 1, n)]
	local k = 0
	if b ~= a and b.t > a.t then
		k = ease(b.e, math.clamp((t - a.t) / (b.t - a.t), 0, 1))
	end
	for j, va in pairs(a.vals) do
		local vb = b.vals[j]
		local o = out[j]
		if not o then
			o = {}
			out[j] = o
		end
		for fi = 1, 6 do o[fi] = va[fi] + (vb[fi] - va[fi]) * k end
	end
	return out
end

function Poses.get(name)
	return A[name]
end

return Poses
